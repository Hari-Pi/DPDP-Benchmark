"""Username/password access control for the DPDP RAG server.

Design notes (security):
- Credentials are never stored in plaintext: .env holds a per-deployment
  random salt and a PBKDF2-HMAC-SHA256 hash (600k iterations) generated by
  scripts/hash_auth.py. Verification is constant-time against the hash.
- Successful logins mint a random 256-bit session token held in memory only
  (server restart = all sessions invalid). Sessions slide 7 days and are
  carried by an HttpOnly, SameSite=Lax cookie (Secure over HTTPS).
- Login attempts are rate limited per client IP (behind Cloudflare the real
  IP arrives via CF-Connecting-IP): 5 failures within 10 minutes locks that
  IP out for 10 minutes.
"""
import hashlib
import hmac
import os
import secrets
import threading
import time
from collections import defaultdict, deque
from datetime import datetime, timedelta, timezone

PBKDF2_ITERATIONS = 600_000
SESSION_TTL = timedelta(days=7)
RATE_WINDOW = 600.0        # seconds
RATE_MAX_FAILURES = 5
RATE_LOCKOUT = 600.0

USER = os.environ.get("DPDP_USER", "").strip()
SALT = os.environ.get("DPDP_AUTH_SALT", "").strip()
HASH = os.environ.get("DPDP_AUTH_HASH", "").strip()
AUTH_ENABLED = bool(USER and SALT and HASH)

_sessions: dict[str, float] = {}          # token -> expiry epoch
_lock = threading.Lock()
_failures: dict[str, deque] = defaultdict(deque)
_lockouts: dict[str, float] = {}
_guard = threading.Lock()


def verify_credentials(username: str, password: str) -> bool:
    """Constant-time credential check against the stored PBKDF2 hash."""
    if not AUTH_ENABLED:
        return True
    if not username or not password:
        return False
    candidate = hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), bytes.fromhex(SALT),
        PBKDF2_ITERATIONS)
    user_ok = hmac.compare_digest(username, USER)
    pass_ok = hmac.compare_digest(candidate.hex(), HASH)
    return user_ok and pass_ok


# ------------------------------------------------------------------ sessions

def create_session() -> str:
    token = secrets.token_urlsafe(32)
    with _lock:
        _sessions[token] = (datetime.now(timezone.utc) + SESSION_TTL).timestamp()
    return token


def session_valid(token: str) -> bool:
    if not AUTH_ENABLED or not token:
        return False
    now = time.time()
    with _lock:
        expiry = _sessions.get(token)
        if expiry is None or expiry < now:
            _sessions.pop(token, None)
            return False
        _sessions[token] = (datetime.now(timezone.utc) + SESSION_TTL).timestamp()
        if len(_sessions) > 1000:  # hard cap; drop oldest expired entries
            for t in [t for t, e in _sessions.items() if e < now]:
                _sessions.pop(t, None)
    return True


def revoke_session(token: str) -> None:
    with _lock:
        _sessions.pop(token, None)


# ------------------------------------------------------------- rate limiting

def _client_ip_ip_key(ip: str) -> str:
    return ip or "unknown"


def login_allowed(ip: str) -> tuple[bool, int]:
    """(allowed, seconds until the lockout lifts)."""
    key = _client_ip_ip_key(ip)
    now = time.time()
    with _guard:
        until = _lockouts.get(key, 0)
        if until > now:
            return False, int(until - now) + 1
        window = _failures.get(key)
        if window:
            while window and now - window[0] > RATE_WINDOW:
                window.popleft()
            if len(window) >= RATE_MAX_FAILURES:
                _lockouts[key] = now + RATE_LOCKOUT
                window.clear()
                return False, int(RATE_LOCKOUT) + 1
    return True, 0


def login_failed(ip: str) -> None:
    key = _client_ip_ip_key(ip)
    now = time.time()
    with _guard:
        window = _failures[key]
        window.append(now)
        while window and now - window[0] > RATE_WINDOW:
            window.popleft()
        if len(window) >= RATE_MAX_FAILURES:
            _lockouts[key] = now + RATE_LOCKOUT
            window.clear()


def login_reset(ip: str) -> None:
    key = _client_ip_ip_key(ip)
    with _guard:
        _failures.pop(key, None)
        _lockouts.pop(key, None)
